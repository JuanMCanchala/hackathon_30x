// Build compositions/<id>.html from each scene fragment in src/scenes/, wrapping it in the
// sub-composition template with the shared kit (src/kit.css, src/kit.js).
//
// A fragment starts with  <!-- scene {"id":"f03-radar","duration":9} -->  and may carry
//   <!-- sfx [{"t":1.2,"type":"whoosh"}, …] -->   scene-local sound cues (tools/audio reads them)
// then its own <style>, the markup that goes inside the scene root, and one <script> that builds
// `tl` (a paused timeline already created for it) with access to `root`, `K` and `$`/`$$`.
//
//   node tools/build-scenes.mjs
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const kitCss = readFileSync(join(root, 'src/kit.css'), 'utf8');
const kitJs = readFileSync(join(root, 'src/kit.js'), 'utf8');
mkdirSync(join(root, 'compositions'), { recursive: true });

const scenes = [];
for (const file of readdirSync(join(root, 'src/scenes')).filter((f) => f.endsWith('.html')).sort()) {
  const src = readFileSync(join(root, 'src/scenes', file), 'utf8');
  const head = src.match(/<!--\s*scene\s+(\{[\s\S]*?\})\s*-->/);
  if (!head) throw new Error(`${file}: missing <!-- scene {...} --> header`);
  const meta = JSON.parse(head[1]);
  const sfxMatch = src.match(/<!--\s*sfx\s+(\[[\s\S]*?\])\s*-->/);
  const sfx = sfxMatch ? JSON.parse(sfxMatch[1]) : [];
  const style = [...src.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join('\n');
  // __CAPTURE_<take> inlines that take's pointer log (assets/capture/<take>.json) at build time.
  const script = [...src.matchAll(/<script>([\s\S]*?)<\/script>/g)]
    .map((m) => m[1])
    .join('\n')
    .replace(/__CAPTURE_(\w+)/g, (_, take) => readFileSync(join(root, 'assets/capture', `${take}.json`), 'utf8').trim());
  const markup = src
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<style>[\s\S]*?<\/style>/g, '')
    .replace(/<script>[\s\S]*?<\/script>/g, '')
    .trim();
  const { id, duration } = meta;

  const html = `<!doctype html>
<html lang="es">
  <head>
    <meta charset="UTF-8" />
    <!-- Generated by tools/build-scenes.mjs from src/scenes/${file}. Edit the fragment, not this file. -->
  </head>
  <body>
    <template>
      <style>
${kitCss.replace('.k-scene {', `#${id} {`)}
${style}
      </style>
      <div id="${id}" data-composition-id="${id}" data-width="1920" data-height="1080" data-duration="${duration}">
${markup}
      </div>
      <script>
        (() => {
${kitJs}
          const root = document.getElementById('${id}');
          const $ = (sel) => root.querySelector(sel);
          const $$ = (sel) => [...root.querySelectorAll(sel)];
          const tl = gsap.timeline({ paused: true });
${script}
          window.__timelines['${id}'] = tl;
        })();
      </script>
    </template>
  </body>
</html>
`;
  writeFileSync(join(root, 'compositions', `${id}.html`), html);
  scenes.push({ id, file, duration, start: meta.start, sfx });
}
writeFileSync(join(root, 'compositions/scenes.json'), JSON.stringify(scenes, null, 2));
console.log(scenes.map((s) => `${s.id} ${s.duration}s, ${s.sfx.length} cues`).join('\n'));
